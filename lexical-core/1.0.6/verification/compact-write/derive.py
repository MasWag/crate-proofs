#!/usr/bin/env python3.11
"""Reproduce/check the explicit u8/decimal specialization; never edit release source."""
from pathlib import Path
import argparse
import hashlib
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
REGISTRY = ROOT / ".work/cargo-home/registry/src/index.crates.io-1949cf8c6b5b557f"


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def function(text, needle):
    start = text.index(needle)
    opening = text.index("{", start)
    depth = 1
    end = opening + 1
    while depth:
        depth += (text[end] == "{") - (text[end] == "}")
        end += 1
    return text[start:end]


def derived_source():
    compact = REGISTRY / "lexical-write-integer-1.0.6/src/compact.rs"
    digit = REGISTRY / "lexical-util-1.0.7/src/digit.rs"
    assert digest(compact) == "0e0359f95417c6e0369fb30d0922dc058c5c9be063f99ff1fb3096d3bb0af9ea", "compact source changed"
    assert digest(digit) == "86227078cc9e31ae03cdd736af04fa023c2ab6d16e1bd6ec4f1f7cd82267fac8", "digit table source changed"
    algorithm = REGISTRY / "lexical-util-1.0.7/src/algorithm.rs"
    assert digest(algorithm) == "e4ac690ace5036e1075bc49847cd32512f3b35b13a6261177af440374e14d4ab", "copy helper source changed"
    assert "dst[..src.len()].copy_from_slice(src);\n\n    src.len()" in algorithm.read_text()
    # The complete source identity is retained alongside the generated input.
    body = function(compact.read_text(), "fn compact(self, radix: u32, buffer: &mut [u8]) -> usize")
    body = body.replace("fn compact(self, radix: u32, buffer: &mut [u8]) -> usize", "pub fn decimal_u8(self_value: u8, buffer: &mut [u8]) -> usize")
    body = body.replace("        assert!(Self::BITS <= 128);\n", "")
    body = body.replace("Self::from_u32(radix)", "10u8").replace("let mut value = self;", "let mut value = self_value;")
    body = body.replace("u32::as_cast(r)", "r as u32")
    body = body.replace("        copy_to_dst(buffer, slc)", "        let len = slc.len();\n        buffer[..len].copy_from_slice(slc);\n        len")
    body = body.replace("\n    ", "\n")
    table = function(digit.read_text(), "pub fn digit_to_char(digit: u32) -> u8").replace("pub fn", "fn", 1)
    prefix = "// Derived u8/decimal input; generated by verification/compact-write/derive.py.\n// Release source and dependency source remain unchanged.\n\npub fn release_compact_u8(value: u8, buffer: &mut [u8]) -> usize {\n    lexical_write_integer::compact::Compact::compact(value, 10, buffer)\n}\n\n"
    return prefix + body + "\n\n" + table + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    expected = derived_source()
    destination = HERE / "src/lib.rs"
    if args.write:
        destination.write_text(expected)
    elif destination.read_text() != expected:
        sys.exit("derived compact writer differs from the pinned transformation recipe")
    print("Derived compact u8 source matches the explicit release transformation recipe.")


if __name__ == "__main__":
    main()
